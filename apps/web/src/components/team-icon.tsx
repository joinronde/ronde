import {
  Briefcase,
  Building2,
  Calculator,
  Camera,
  ChartLine,
  Code2,
  Database,
  FlaskConical,
  Globe,
  GraduationCap,
  Handshake,
  HardHat,
  Headphones,
  Heart,
  Leaf,
  type LucideIcon,
  Megaphone,
  Palette,
  PenTool,
  Rocket,
  Scale,
  Server,
  ShieldCheck,
  ShoppingCart,
  Smartphone,
  Stethoscope,
  Truck,
  Users,
  Wrench,
} from "lucide-react";
import type { TeamIconName } from "@/lib/shared/team-icons";

const DRAWINGS: Record<TeamIconName, LucideIcon> = {
  users: Users,
  code: Code2,
  server: Server,
  smartphone: Smartphone,
  database: Database,
  shield: ShieldCheck,
  palette: Palette,
  pen: PenTool,
  camera: Camera,
  megaphone: Megaphone,
  chart: ChartLine,
  briefcase: Briefcase,
  calculator: Calculator,
  scale: Scale,
  cart: ShoppingCart,
  truck: Truck,
  headphones: Headphones,
  handshake: Handshake,
  graduation: GraduationCap,
  flask: FlaskConical,
  stethoscope: Stethoscope,
  hardhat: HardHat,
  wrench: Wrench,
  leaf: Leaf,
  building: Building2,
  globe: Globe,
  rocket: Rocket,
  heart: Heart,
};

/** A team's drawing (a group of people when it has none) */
export function TeamIcon({ name, size = 18 }: { name?: string | null; size?: number }) {
  const Drawing = DRAWINGS[name as TeamIconName] ?? Users;
  return <Drawing size={size} strokeWidth={2} aria-hidden="true" />;
}
