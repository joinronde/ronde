// Writes src/messages.ts: one static import per namespace and locale, so bundlers can follow them.
// Run with `pnpm --filter @ronde/i18n generate` after adding a namespace file in messages/<locale>/.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const locales = readdirSync(path.join(root, "messages")).sort();
const namespaces = readdirSync(path.join(root, "messages", "en"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.slice(0, -5))
  .sort();
const id = (locale, ns) => `${locale}_${ns.replace(/[^a-zA-Z0-9]/g, "_")}`;

const lines = ["// Generated by scripts/generate.mjs: do not edit by hand.", ""];
for (const locale of locales) for (const ns of namespaces) lines.push(`import ${id(locale, ns)} from "../messages/${locale}/${ns}.json";`);
lines.push("");
for (const locale of locales) {
  lines.push(`const ${locale} = {`);
  for (const ns of namespaces) lines.push(`  ${JSON.stringify(ns)}: ${id(locale, ns)},`);
  lines.push("};");
}
lines.push("");
lines.push("/** Messages of the default locale: their shape is the reference for every other locale */");
lines.push("export type Messages = typeof en;");
lines.push("");
lines.push(`export const messages: Record<${locales.map((l) => JSON.stringify(l)).join(" | ")}, Messages> = { ${locales.join(", ")} };`);
lines.push(`export const namespaces = ${JSON.stringify(namespaces)} as const;`);
const out = path.join(root, "src", "messages.ts");
writeFileSync(out, lines.join("\n") + "\n");
// Laid out by the repository's formatter, so a regenerated file passes the lint as it is
execFileSync(path.resolve(root, "../../node_modules/.bin/biome"), ["format", "--write", out], { stdio: "ignore" });
console.log(`messages.ts: ${locales.length} locales × ${namespaces.length} namespaces`);
